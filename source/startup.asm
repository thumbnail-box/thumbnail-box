; ============================================================================
; startup.asm — 「冬の窓」起動用メインプログラム
; ============================================================================
;
; 動作：
;   1. CopperリストのアドレスをCop1LCレジスタに設定
;   2. Copperを有効化
;   3. 無限ループ（プログラム終了なし）
;
; ============================================================================

        SECTION code:start

       .globl _main

_main:
        ; ───────────────────────────────────────────────────────────────────────
        ; ステップ1: WinterWindowのアドレスを取得
        ; ───────────────────────────────────────────────────────────────────────
        lea     WinterWindow,a0         ; コッパーリストのアドレス
                                        ; winter.asm で定義された外部シンボル
        
        ; ───────────────────────────────────────────────────────────────────────
        ; ステップ2: Copperリストをロード
        ; ───────────────────────────────────────────────────────────────────────
        move.l  a0,$DFF080              ; Cop1LC（Copperリスト1）
        move.l  a0,$DFF084              ; Cop2LC（冗長用）
        
        ; ───────────────────────────────────────────────────────────────────────
        ; ステップ3: Copperを有効化
        ; ──────────────────────────────────────────────────────────────────────
        move.w  #$8000,$DFF096          ; COPPER_ENABLE（最上位ビット=1）
        
        ; ───────────────────────────────────────────────────────────────────────
        ; ステップ4: 無限ループ（終了しない）
        ; ───────────────────────────────────────────────────────────────────────
Loop:
        jmp     Loop                    ; 永遠に待機

        even                            ; アライメント調整

; ──────────────────────────────────────────────────────────────────────────────
; 外部シンボルの宣言（winter.asm から参照）
; ──────────────────────────────────────────────────────────────────────────────
        extern WinterWindow

        END
