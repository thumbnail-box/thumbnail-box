; ============================================================================
; 冬の窓 — Copper Haiku Series No.1
; ============================================================================
; 
; 
; 冬窓に光の一筋だけ
; 灰白の空と橙の灯り
; 夜は青く静かに沈む
;
; 
; 対応機種: Amiga A500 (OCS) 以上
; モード    : 320×256, 32色同時表示
; フレーム  : 1フレームで完結（50Hz PAL）
; 使用レジスタ: $DFF180 (COLOR00) — 背景色
;
; 
; WAIT命令 = 「間（ま）」の沈黙
; MOVE命令 = 「筆致」の変化
; 走査線番号 = 「季節の位置」
;
; ============================================================================

        SECTION code:copper_haiku

; ----------------------------------------------------------------------------
; コッパーリスト開始 — 「冬の窓」全篇
; ----------------------------------------------------------------------------

WinterWindow:

; ──────────────────────────────────────────────────────────────────────────────
; 第1句：五 — 灰白の朝（上部の余白）
; 「272ラインまで、ただ待つこと」
; ──────────────────────────────────────────────────────────────────────────────

        dc.w  $8018,$0141           ; MOVE $DFF180へ待機アドレスを設定
        dc.w  $0110,$0FE0           ; WAIT 272番目の走査線まで（垂直位置）
                                    ; ここに「冬の長い夜明け前の時間」がある
        dc.w  $DFF180,$0080         ; MOVE COLOR00 = 淡い灰色 ($0080)
                                    ; 「灰白の空」—— 冬の朝の薄明
        dc.w  $0000,$0FE0           ; WAIT 272番目と同じ位置（次の行へ準備）

; ──────────────────────────────────────────────────────────────────────────────
; 第2句：七 — 光の一筋（中央部の焦点）
; 「17走査線分の、小さな輝き」
; ──────────────────────────────────────────────────────────────────────────────

        dc.w  $0122,$0FE0           ; WAIT 290番目へ（中部へ移動）
                                    ; 「光の入り口」
        dc.w  $DFF180,$0F60         ; MOVE COLOR00 = 淡い橙色 ($0F60)
                                    ; 「窓から差し込む一筋の夕陽」
        dc.w  $0124,$0FE0           ; WAIT 292番目
        dc.w  $DFF180,$0F60         ; MOVE 同上（持続）
        dc.w  $0126,$0FE0           ; WAIT 294番目
        dc.w  $DFF180,$0F60         ; MOVE 同上
        dc.w  $0128,$0FE0           ; WAIT 296番目
        dc.w  $DFF180,$0F60         ; MOVE 同上
        dc.w  $012A,$0FE0           ; WAIT 298番目
        dc.w  $DFF180,$0F60         ; MOVE 同上（7行の「七」）
        dc.w  $012C,$0FE0           ; WAIT 300番目

; ──────────────────────────────────────────────────────────────────────────────
; 第3句：五 — 青い夜（下部の沈黙）
; 「13走査線で、全てを沈める」
; ──────────────────────────────────────────────────────────────────────────────

        dc.w  $0130,$0FE0           ; WAIT 304番目へ（下部へ移動）
                                    ; 「暮れの始まり」
        dc.w  $DFF180,$0222         ; MOVE COLOR00 = 深い青 ($0222)
                                    ; 「すべて青く静かに沈む」
        dc.w  $0132,$0FE0           ; WAIT 306番目
        dc.w  $DFF180,$0222         ; MOVE 同上
        dc.w  $0134,$0FE0           ; WAIT 308番目
        dc.w  $DFF180,$0222         ; MOVE 同上
        dc.w  $0136,$0FE0           ; WAIT 310番目
        dc.w  $DFF180,$0222         ; MOVE 同上
        dc.w  $0138,$0FE0           ; WAIT 312番目
        dc.w  $DFF180,$0222         ; MOVE 同上（5行の「五」）

; ──────────────────────────────────────────────────────────────────────────────
; 終止符 — 無限ループ（次のフレームへ）
; 「句が終わっても、時間は続く」
; ──────────────────────────────────────────────────────────────────────────────

        dc.w  $FFFF,$FFFE           ; JMP -$0002（垂直帰線待ち・無限ループ）
                                    ; これが「切れ字」—— 作品の終わり

; ----------------------------------------------------------------------------
; コッパーリスト終了
; ----------------------------------------------------------------------------

; ──────────────────────────────────────────────────────────────────────────────
; 
; ──────────────────────────────────────────────────────────────────────────────
;
; $0080 (灰白) = R:0 G:8 B:0
;   → 春ではない、冬の朝の冷たい空気
;
; $0F60 (橙色) = R:F G:6 B:0
;   → 唯一の温もり、窓からの光
;
; $0222 (深青) = R:2 G:2 B:2
;   → 夜の静寂、すべてが青白く凍る
;
; ──────────────────────────────────────────────────────────────────────────────
; 
; ──────────────────────────────────────────────────────────────────────────────
; 1. VASMでコンパイル: vasm68k -Fhunkbin winter.asm -o winter.bin
; 2. WinUAEでロード: Copperリストのアドレスを$DFF080に設定
; 3. フレームが自動的にループし、永遠に「冬」が続く
;
; ──────────────────────────────────────────────────────────────────────────────

        END
